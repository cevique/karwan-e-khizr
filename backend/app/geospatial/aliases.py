ALL_ALIASES: dict[str, list[str]] = {}
for stop_key, aliases in STOP_ALIASES.items():
    ALL_ALIASES[stop_key] = aliases


def resolve_alias(text: str) -> Optional[str]:
    normalized = text.lower().strip()
    for stop_key, aliases in STOP_ALIASES.items():
        if normalized == stop_key.lower():
            return stop_key
        for alias in aliases:
            if normalized == alias.lower():
                return stop_key
    return None


def get_landmark_coords(text: str) -> Optional[tuple[float, float]]:
    normalized = text.lower().strip()
    return LANDMARK_ALIASES.get(normalized)